// lib/db.ts
// GhostDocs IndexedDB schema using Dexie.js.
// Single source of truth for all persistent state: documents, chunks,
// embeddings, timelines, answers, and Time Capsules.
// Schema migrations are handled via Dexie version increments — never drop
// and recreate the DB.

import Dexie, { type Table } from 'dexie';

// ─── Document ──────────────────────────────────────────────────────────────

export type DocumentStatus =
  | 'pending'
  | 'parsing'
  | 'chunking'
  | 'embedding'
  | 'complete'
  | 'error';

export type DocumentType = 'pdf' | 'markdown' | 'plaintext';

export interface DocumentMetadata {
  title: string | null;
  detectedDate: string | null;  // ISO 8601 string or null
  author: string | null;
  documentType: DocumentType;
}

export interface DocumentRecord {
  slug: string;                  // Primary key — URL-safe, stable identifier
  filename: string;
  mimeType: string;
  sizeBytes: number;
  status: DocumentStatus;
  metadata: DocumentMetadata;
  summary: string | null;        // Generated by the Archivist (1–200 words)
  ingestedAt: number;            // Unix timestamp ms
  pageCount: number | null;      // PDFs only; null for Markdown/TXT
  skippedPages: number[];        // Corrupt/unreadable page numbers (1-indexed)
  errorMessage: string | null;
}

// ─── Chunk ─────────────────────────────────────────────────────────────────

export type EmbeddingStatus = 'pending' | 'complete' | 'embedding_failed';

export interface ChunkRecord {
  chunkId: string;               // Primary key — `${slug}-chunk-${index}`
  documentId: string;            // Foreign key → DocumentRecord.slug
  text: string;
  pageNumber: number | null;     // PDFs: 1-indexed page number; null for others
  lineOffset: number | null;     // Markdown/TXT: 0-indexed line of first token
  tokenCount: number;            // 1–512 (whitespace-delimited words)
  truncated: boolean;            // true if the chunk was truncated to 512 tokens
  chunkIndex: number;            // 0-indexed position within the document
  embeddingStatus: EmbeddingStatus;
}

// ─── Embedding ─────────────────────────────────────────────────────────────

export interface EmbeddingRecord {
  chunkId: string;               // Primary key — matches ChunkRecord.chunkId
  vector: Float32Array;          // 384-dimensional (ghostdocs-lexical-hash-384-v1, L2-normalised)
}

// ─── Citation ──────────────────────────────────────────────────────────────

export interface CitationRecord {
  chunkId: string;
  documentName: string;          // filename as stored in DocumentRecord
  pageNumber: number | null;     // PDFs only
  lineSection: string | null;    // Markdown/TXT: "line 42" or section heading
  excerpt: string;               // Verbatim excerpt ≤ 50 words from chunk.text
}

// ─── Timeline Entry ────────────────────────────────────────────────────────

export interface TimelineEntryRecord {
  entryId: string;               // Primary key — UUID v4
  eventDescription: string;     // ≤ 500 characters
  resolvedDate: string | null;   // ISO 8601 date string; null for unresolved signals
  resolvedDateEnd: string | null; // ISO 8601 for date ranges; null for point dates
  confidenceScore: number;       // [0.0, 1.0]
  citations: CitationRecord[];
  uncertaintyNotice: string | null; // Plain-language explanation for < fully confident
  isImplicit: boolean;           // true for unresolved temporal signals
  sessionId: string;             // Groups entries by ingestion session
}

// ─── Answer ────────────────────────────────────────────────────────────────

export interface AnswerRecord {
  answerId: string;              // Primary key — UUID v4
  questionText: string;
  synthesisedText: string;
  citations: CitationRecord[];
  confidenceScore: number;       // [0.0, 1.0] — arithmetic mean of chunk similarities
  uncertaintyNotice: string | null;
  createdAt: number;             // Unix timestamp ms
  chunkIds: string[];            // The top-5 chunkIds used for synthesis
}

// ─── Time Capsule ──────────────────────────────────────────────────────────

export interface CapsuleBundledData {
  documents: DocumentRecord[];
  chunks: ChunkRecord[];
  // Float32Array → number[] for JSON serialisation; restored on import
  embeddings: Array<{ chunkId: string; vector: number[] }>;
  timelineEntries: TimelineEntryRecord[];
}

export interface CapsuleRecord {
  capsuleId: string;             // Primary key — UUID v4
  capsuleVersion: number;        // Positive integer; increments on breaking schema changes
  createdAt: number;             // Unix timestamp ms
  documentCount: number;
  exportFilename: string;        // Default: ghostdocs-capsule-{YYYY-MM-DD}.json
  bundledData: CapsuleBundledData;
}

// ─── Database Class ────────────────────────────────────────────────────────

export class GhostDocsDB extends Dexie {
  documents!: Table<DocumentRecord, string>;   // keyed by slug
  chunks!: Table<ChunkRecord, string>;         // keyed by chunkId
  embeddings!: Table<EmbeddingRecord, string>; // keyed by chunkId
  timelines!: Table<TimelineEntryRecord, string>; // keyed by entryId
  answers!: Table<AnswerRecord, string>;        // keyed by answerId
  capsules!: Table<CapsuleRecord, string>;      // keyed by capsuleId

  constructor() {
    super('GhostDocsDB');

    this.version(1).stores({
      // documents: primary key = slug; secondary indices on status and ingestedAt
      documents: 'slug, status, ingestedAt',

      // chunks: primary key = chunkId; compound index [documentId+chunkIndex]
      // for efficient ordered retrieval per document
      chunks: 'chunkId, documentId, embeddingStatus, chunkIndex, [documentId+chunkIndex]',

      // embeddings: primary key = chunkId (no secondary indices needed)
      embeddings: 'chunkId',

      // timelines: primary key = entryId; resolvedDate indexed for range queries
      // isImplicit indexed for filtering unresolved entries
      timelines: 'entryId, resolvedDate, sessionId, isImplicit',

      // answers: primary key = answerId; createdAt for chronological listing
      answers: 'answerId, createdAt',

      // capsules: primary key = capsuleId; indices for version management
      capsules: 'capsuleId, createdAt, capsuleVersion',
    });
  }
}

// Export singleton instance — import this in all application code
export const db = new GhostDocsDB();
